if not os.path.exists(rotated_images_dir):
    print(f"Error: Directory '{rotated_images_dir}' does not exist. Please check the extraction.")
else:
    for filename in sorted(os.listdir(rotated_images_dir)):
        if not filename.lower().endswith(supported_formats):
            print(f"Skipping unsupported file: {filename}")
            continue

        rotated_image_path = os.path.join(rotated_images_dir, filename)
        print(f"Processing rotated image: {rotated_image_path}")

        best_match_idx, rotation_angle, rotated_histogram = process_rotated_image(rotated_image_path, original_histograms)
        if rotated_histogram is None:
            print(f"Error processing rotated image: {filename}")
            continue

        print(f"Rotated image '{filename}' matches with original image index {best_match_idx} with an estimated rotation angle of {rotation_angle} degrees.")

        # Visualize histograms
        def plot_histogram(histogram, title, subtitle=None):
            if histogram is None or not isinstance(histogram, np.ndarray):
                print(f"Invalid histogram provided for plotting: {title}")
                return
            plt.figure(figsize=(12, 5))
            plt.bar(np.arange(len(histogram)), histogram, width=1, color='blue')
            plt.title(title)
            if subtitle:
                plt.suptitle(subtitle, fontsize=10, color="red")
            plt.xlabel('Orientation (Degrees)')
            plt.ylabel('Accumulated line length')
            plt.xticks(np.arange(0, 360, 30), labels=[f"{i}" for i in range(0, 360, 30)])  # Labels every 30 degrees for clarity
            plt.xlim([0, 359])
            plt.show()

        # Plot histograms for the matched images
        subtitle_text = f"Rotated image '{filename}' matches with original image index {best_match_idx} with an estimated rotation angle of {rotation_angle} degrees."
        plot_histogram(original_histograms[best_match_idx], 'Original Image Histogram (1 Degree Intervals)', subtitle=subtitle_text)
