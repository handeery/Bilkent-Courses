    if rotated_image is None:
        print(f"Error: Unable to load rotated image at {rotated_image_path}.")
        return None, None, None

    edges = detect_edges(rotated_image)
    lines = detect_lines(edges)
    rotated_histogram = calculate_orientation_histogram(lines)

    # Ensure rotated_histogram is a valid array
    if rotated_histogram is None or not isinstance(rotated_histogram, np.ndarray):
        print(f"Error: Failed to compute histogram for {rotated_image_path}.")
        return None, None, None

    best_match_idx, rotation_angle, _ = find_best_match(rotated_histogram, original_histograms, degree_interval=1)
    return best_match_idx, rotation_angle, rotated_histogram

