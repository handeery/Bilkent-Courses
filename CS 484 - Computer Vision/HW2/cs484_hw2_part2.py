def compute_gabor_responses(img, gabor_filters):
    responses = []
    for kernel in gabor_filters:
        response = cv2.filter2D(img, cv2.CV_32F, kernel)
        responses.append(np.abs(response))  # Use the magnitude of the response
    return responses

# Function to compute average Gabor features for superpixels
def compute_superpixel_gabor_features(labels, gabor_responses):
    unique_labels = np.unique(labels)
    features = []
    for label in unique_labels:
        mask = (labels == label)
        avg_features = [np.mean(response[mask]) for response in gabor_responses]
        features.append(avg_features)
    return np.array(features)

# Main workflow
image_dir = '/content/images'  # Path where your images are stored
images, filenames = load_images_from_folder(image_dir)

# Parameters for SLIC
n_segments = 200  # Number of superpixels
compactness = 20  # Compactness parameter for SLIC

# Parameters for Gabor filter bank
scales = [4, 8, 16, 32]  # 4 scales
orientations = [0, np.pi/4, np.pi/2, 3*np.pi/4]  # 4 orientations

# Create Gabor filter bank
gabor_filters = create_gabor_filter_bank(scales, orientations)

# Collect all superpixel features from all images
print("Extracting Gabor features and superpixels...")
all_features = []  # To store all superpixel features
all_labels = []  # To store superpixel labels for visualization
image_shapes = []  # To store the shape of each image for reconstruction

for img in images:
    # Convert image to grayscale
    gray_img = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)

    # Generate superpixels
    labels = generate_superpixels(img, n_segments=n_segments, compactness=compactness)
    all_labels.append(labels)
    image_shapes.append(labels.shape)

    # Compute Gabor responses
    gabor_responses = compute_gabor_responses(gray_img, gabor_filters)

    # Compute average Gabor features for each superpixel
    superpixel_features = compute_superpixel_gabor_features(labels, gabor_responses)
    all_features.append(superpixel_features)

# Flatten all features into a single matrix
all_features_flat = np.vstack(all_features)

# Perform K-Means Clustering
n_clusters = 10  # Number of clusters
print(f"Clustering {all_features_flat.shape[0]} superpixels into {n_clusters} clusters...")
kmeans = KMeans(n_clusters=n_clusters, random_state=42)
cluster_labels = kmeans.fit_predict(all_features_flat)

# Visualize clustering results with pseudo-color images
output_dir = '/content/output_pseudo_color'
os.makedirs(output_dir, exist_ok=True)

print("Generating pseudo-color images...")
cluster_index = 0
colors = np.array(plt.colormaps['tab10'](np.linspace(0, 1, n_clusters)))[:, :3]  # Use only RGB values

for img, labels, shape, fname in zip(images, all_labels, image_shapes, filenames):
    pseudo_color_image = np.zeros((*shape, 3), dtype=np.uint8)
