radius2 = 2.5 * np.sqrt(images[0].shape[0] * images[0].shape[1] / n_segments)  # Second-level neighborhood radius

# Generate contextual features for all superpixels
print("Computing contextual features...")
contextual_features_list = []
contextual_labels = []
for img, labels, features in zip(images, all_labels, all_features):
    contextual_features = compute_contextual_features(features, labels, radius1, radius2)
    contextual_features_list.append(contextual_features)
    contextual_labels.append(labels)

# Flatten all contextual features for clustering
all_contextual_features = np.vstack(contextual_features_list)

# Perform K-Means Clustering
n_clusters = 10  # Number of clusters
