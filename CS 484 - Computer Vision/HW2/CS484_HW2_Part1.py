# Canny edge detector function
def detect_edges(image, low_threshold=40, high_threshold=90):
    gray_image = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    edges = cv2.Canny(gray_image, low_threshold, high_threshold)
    return edges

# Hough Line detection function
def detect_lines(edge_image, threshold=15, min_line_length=20, max_line_gap=15):
    lines = cv2.HoughLinesP(edge_image, 1, np.pi / 180, threshold, minLineLength=min_line_length, maxLineGap=max_line_gap)
    line_image = np.zeros((edge_image.shape[0], edge_image.shape[1], 3), dtype=np.uint8)

    if lines is not None:
        for line in lines:
            for x1, y1, x2, y2 in line:
                cv2.line(line_image, (x1, y1), (x2, y2), (0, 255, 0), 2)

    return line_image, lines

# Function to compute line orientation histograms
def compute_line_orientation_histogram(lines):
    num_bins = 72  # 360/5 = 72 bins for 5-degree intervals
    orientations = np.linspace(-180, 180, num_bins + 1)
    histogram = np.zeros(num_bins)

    if lines is None:
        return histogram, orientations

    for line in lines:
        for x1, y1, x2, y2 in line:
            angle = np.degrees(np.arctan2(y2 - y1, x2 - x1))
            angle = (angle + 180) % 360 - 180  # Normalize angle to the range [-180, 180)
            bin_idx = int((angle + 180) // (360 / num_bins))  # Find the corresponding bin
            line_length = np.sqrt((x2 - x1)**2 + (y2 - y1)**2)
            histogram[bin_idx] += line_length  # Weight by line length

    return histogram, orientations[:-1]

