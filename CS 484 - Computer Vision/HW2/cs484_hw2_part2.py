import numpy as np
from sklearn.cluster import KMeans
import matplotlib.pyplot as plt
from scipy.spatial.distance import cdist

# Function to compute centroids of superpixels
def compute_superpixel_centroids(labels):
    unique_labels = np.unique(labels)
    centroids = []
    for label in unique_labels:
        mask = (labels == label)
        coords = np.argwhere(mask)
        centroid = np.mean(coords, axis=0)
        centroids.append(centroid)
    return np.array(centroids)

# Function to compute contextual features
def compute_contextual_features(features, labels, radius1, radius2):
    centroids = compute_superpixel_centroids(labels)
    contextual_features = []
    unique_labels = np.unique(labels)

    for idx, label in enumerate(unique_labels):
        mask = (labels == label)
        distances = cdist([centroids[idx]], centroids).flatten()

        # First-level neighbors
        neighbors1 = (distances > 0) & (distances <= radius1)
        features1 = features[neighbors1].mean(axis=0) if np.any(neighbors1) else np.zeros_like(features[0])

        # Second-level neighbors
        neighbors2 = (distances > radius1) & (distances <= radius2)
        features2 = features[neighbors2].mean(axis=0) if np.any(neighbors2) else np.zeros_like(features[0])

        # Concatenate features
        combined_features = np.concatenate([features[idx], features1, features2])
        contextual_features.append(combined_features)

    return np.array(contextual_features)

